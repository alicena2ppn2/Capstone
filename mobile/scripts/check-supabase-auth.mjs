import { readFileSync } from 'node:fs';
import { AUTH_REDIRECT } from '../src/auth/supabaseAuthCore.mjs';
const root=new URL('../',import.meta.url);
const local=readFileSync(new URL('.env.local',root),'utf8');
const values=Object.fromEntries(local.split(/\r?\n/).filter(l=>l.includes('=')).map(l=>{const i=l.indexOf('=');return [l.slice(0,i),l.slice(i+1)];}));
const url=process.env.EXPO_PUBLIC_SUPABASE_URL||values.EXPO_PUBLIC_SUPABASE_URL;
const key=process.env.EXPO_PUBLIC_SUPABASE_PUBLISHABLE_KEY||values.EXPO_PUBLIC_SUPABASE_PUBLISHABLE_KEY;
const config=JSON.parse(readFileSync(new URL('app.json',root),'utf8')).expo;
if(!/^https:\/\/[a-z0-9]+\.supabase\.co$/.test(url||'')||!key?.startsWith('sb_publishable_'))throw Error('Supabase URL/publishable key 설정을 확인해 주세요. secret/service_role 키는 사용할 수 없습니다.');
console.log('Supabase project:',url);
console.log('App callback:',AUTH_REDIRECT);
console.log('iOS bundle:',config.ios.bundleIdentifier);
if(config.scheme!=='capstone-mochi'||!config.ios.bundleIdentifier)throw Error('Scheme/bundle identifier mismatch');
if(config.plugins.some(p=>typeof p==='string'&&(/firebase|nitro-google/.test(p))))throw Error('Obsolete native Firebase plugin');
const response=await fetch(`${url}/auth/v1/settings`,{headers:{apikey:key},signal:AbortSignal.timeout(15000)});
if(!response.ok)throw Error(`Supabase auth settings request failed (${response.status})`);
const settings=await response.json();console.log('Google provider:',!!settings.external?.google);
if(!settings.external?.google)throw Error('Google provider is not enabled on this Supabase project');
console.log('PASS public settings/config. Redirect allowlist, OAuth consent and real device login require console/device verification.');
